CREATE TABLE jp_teacher (
    id BIGINT NOT NULL,
    institution_id BIGINT NOT NULL,
    campus_id BIGINT NULL,
    teacher_code VARCHAR(64) NOT NULL,
    teacher_name VARCHAR(128) NOT NULL,
    phone VARCHAR(32) NULL,
    gender VARCHAR(16) NULL,
    title VARCHAR(64) NULL,
    employment_type VARCHAR(32) NOT NULL DEFAULT 'full_time',
    status VARCHAR(32) NOT NULL DEFAULT 'active',
    hired_at DATE NULL,
    remark VARCHAR(500) NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NULL,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    updated_by BIGINT NULL,
    deleted TINYINT(1) NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_jp_teacher_code (institution_id, teacher_code),
    UNIQUE KEY uk_jp_teacher_phone (institution_id, phone),
    CONSTRAINT fk_jp_teacher_institution FOREIGN KEY (institution_id) REFERENCES jp_institution (id),
    CONSTRAINT fk_jp_teacher_campus FOREIGN KEY (campus_id) REFERENCES jp_campus (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE jp_student (
    id BIGINT NOT NULL,
    institution_id BIGINT NOT NULL,
    campus_id BIGINT NULL,
    student_no VARCHAR(64) NOT NULL,
    student_name VARCHAR(128) NOT NULL,
    gender VARCHAR(16) NULL,
    birthday DATE NULL,
    guardian_name VARCHAR(128) NULL,
    guardian_phone VARCHAR(32) NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'studying',
    enrolled_at DATE NULL,
    remark VARCHAR(500) NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NULL,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    updated_by BIGINT NULL,
    deleted TINYINT(1) NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_jp_student_no (institution_id, student_no),
    CONSTRAINT fk_jp_student_institution FOREIGN KEY (institution_id) REFERENCES jp_institution (id),
    CONSTRAINT fk_jp_student_campus FOREIGN KEY (campus_id) REFERENCES jp_campus (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE jp_class (
    id BIGINT NOT NULL,
    institution_id BIGINT NOT NULL,
    campus_id BIGINT NOT NULL,
    term_id BIGINT NULL,
    class_code VARCHAR(64) NOT NULL,
    class_name VARCHAR(128) NOT NULL,
    teacher_id BIGINT NULL,
    capacity_limit INT NOT NULL DEFAULT 0,
    current_students INT NOT NULL DEFAULT 0,
    status VARCHAR(32) NOT NULL DEFAULT 'planning',
    opened_at DATE NULL,
    remark VARCHAR(500) NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NULL,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    updated_by BIGINT NULL,
    deleted TINYINT(1) NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_jp_class_code (campus_id, class_code),
    UNIQUE KEY uk_jp_class_name (campus_id, class_name),
    CONSTRAINT fk_jp_class_institution FOREIGN KEY (institution_id) REFERENCES jp_institution (id),
    CONSTRAINT fk_jp_class_campus FOREIGN KEY (campus_id) REFERENCES jp_campus (id),
    CONSTRAINT fk_jp_class_term FOREIGN KEY (term_id) REFERENCES jp_term (id),
    CONSTRAINT fk_jp_class_teacher FOREIGN KEY (teacher_id) REFERENCES jp_teacher (id),
    CONSTRAINT chk_jp_class_capacity CHECK (capacity_limit >= 0),
    CONSTRAINT chk_jp_class_students CHECK (current_students >= 0 AND current_students <= capacity_limit)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
