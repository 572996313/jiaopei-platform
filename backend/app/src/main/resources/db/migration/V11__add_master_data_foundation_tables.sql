CREATE TABLE jp_course_category (
    id BIGINT NOT NULL,
    institution_id BIGINT NOT NULL,
    category_code VARCHAR(64) NOT NULL,
    category_name VARCHAR(128) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'active',
    sort_order INT NOT NULL DEFAULT 0,
    remark VARCHAR(500) NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NULL,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    updated_by BIGINT NULL,
    deleted TINYINT(1) NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_jp_course_category_code (institution_id, category_code),
    UNIQUE KEY uk_jp_course_category_name (institution_id, category_name),
    CONSTRAINT fk_jp_course_category_institution FOREIGN KEY (institution_id) REFERENCES jp_institution (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE jp_course (
    id BIGINT NOT NULL,
    institution_id BIGINT NOT NULL,
    category_id BIGINT NULL,
    course_code VARCHAR(64) NOT NULL,
    course_name VARCHAR(128) NOT NULL,
    subject_name VARCHAR(64) NULL,
    teaching_method VARCHAR(32) NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'active',
    remark VARCHAR(500) NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NULL,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    updated_by BIGINT NULL,
    deleted TINYINT(1) NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_jp_course_code (institution_id, course_code),
    UNIQUE KEY uk_jp_course_name (institution_id, course_name),
    KEY idx_jp_course_category (category_id),
    CONSTRAINT fk_jp_course_institution FOREIGN KEY (institution_id) REFERENCES jp_institution (id),
    CONSTRAINT fk_jp_course_category FOREIGN KEY (category_id) REFERENCES jp_course_category (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

