--
-- 与 cornerstone-core jar 内的 cornerstone/migration/V111__seed_navigation_menu.sql
-- 是同一批改动的两份落点，两条 INSERT 一字不差（AGENTS「模块装配与开关」的双轨规则）：
-- 教培自己的库从 V1..V92 长起来，cornerstone/migration 那条目录不在本仓库的
-- cornerstone.flyway.locations 里，所以 V111 在教培一条都不会执行；反过来新项目
-- 只跑 V1xx，拿不到本文件。少写任何一份，另一条路径就缺这个入口。
--
-- 这一页解决什么：客户反馈侧边栏"菜单一堆、不知道点哪个"之后，V92 已把分组按
--   "多久用一次"重排；但组名/图标/顺序写在前端登记里，客户自己想调必须改代码。
--   导航编排页把 sys_menu 的一个受限视图开放给现场操作员——只允许改
--   名称 / 图标 / 顺序 / 页面属于哪个分组 / 侧边栏是否显示 这五列，
--   路径、权限码、节点类型、编码一律只读（改那些会造出"点进去 403"或"入口指到不存在的页面"）。
--   「菜单管理」不删：它是平台管理员的全量工具，这一页不取代它。
--
-- 挂码口径（AGENTS「权限码与菜单节点的分配规则」）：
--   这一页读与写共用单码（GET 结构、PUT 保存、POST 新建分组都拦 system:nav:manage），
--   按第 4 条把码挂在**页面节点**上、不再配同名"维护"按钮。与 V62/V105 收口后的
--   用户/角色/字典/数据源/注册凭证/编号规则同一形态。
--
-- 落点选择：父节点 13「低代码配置」（字典 5 / 数据源 11 / 列表配置 7 / 编号规则 138
--   都在这族里），sort_no 50 排在编号规则之后。导航编排改的正是"菜单这一列怎么长出来、
--   怎么排"，属元数据配置，不放「系统运维」（那是参数与留痕）。
--
-- 授权范围：只有平台管理员(id=1)。**不给机构运营(110)**——sys_menu 全平台一份、
--   没有机构列，A 机构改了分组顺序，B 机构看到的也是改后的；这条与 AGENTS 第 8 条
--   "非平台角色一律不给系统设置页"同口径。将来真要下放，前置条件是这张表按机构分范围，
--   那属另一批。
--   不给 sys_role.permission_codes 补 CSV：菜单节点已带这个码，取权限时两条路取并集，
--   再写一份就是 AGENTS 说的"两份账"。
--
-- id 避让：管理端段 1~25、101~123、130~139 已占用，200~215 是小程序端（student/parent）段，
--   本次取 140（SELECT id>=118 核对为空）；sys_role_menu 用 1400000 + 角色 ID 取号，
