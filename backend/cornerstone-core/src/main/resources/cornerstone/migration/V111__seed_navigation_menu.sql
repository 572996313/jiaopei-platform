-- id 避让：本文件属底座基线，下游从零建库时只有 V100~V110 种下的 1~14、18、101~111、
--   115、138 这批，140 未占用；教培侧的 200+ 是它自己的小程序端节点段，底座不碰。
--   sys_role_menu 用 1400000 + 角色 ID 取号，与 V109 的 1380001 同一档。
