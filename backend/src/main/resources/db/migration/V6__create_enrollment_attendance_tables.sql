CREATE TABLE jp_enrollment (
    id BIGINT NOT NULL,
    institution_id BIGINT NOT NULL,
    student_id BIGINT NOT NULL,
    class_id BIGINT NOT NULL,
    enrollment_no VARCHAR(64) NOT NULL,
    channel VARCHAR(32) NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'submitted',
    enrolled_at DATE NOT NULL,
    remark VARCHAR(500) NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NULL,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    updated_by BIGINT NULL,
    deleted TINYINT(1) NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_jp_enrollment_no (institution_id, enrollment_no),
    UNIQUE KEY uk_jp_enrollment_student_class (student_id, class_id),
    CONSTRAINT fk_jp_enrollment_institution FOREIGN KEY (institution_id) REFERENCES jp_institution (id),
    CONSTRAINT fk_jp_enrollment_student FOREIGN KEY (student_id) REFERENCES jp_student (id),
    CONSTRAINT fk_jp_enrollment_class FOREIGN KEY (class_id) REFERENCES jp_class (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE jp_class_student (
    id BIGINT NOT NULL,
    institution_id BIGINT NOT NULL,
    class_id BIGINT NOT NULL,
    student_id BIGINT NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'active',
    joined_at DATE NOT NULL,
    left_at DATE NULL,
    remark VARCHAR(500) NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NULL,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    updated_by BIGINT NULL,
    deleted TINYINT(1) NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_jp_class_student (class_id, student_id),
    CONSTRAINT fk_jp_class_student_institution FOREIGN KEY (institution_id) REFERENCES jp_institution (id),
    CONSTRAINT fk_jp_class_student_class FOREIGN KEY (class_id) REFERENCES jp_class (id),
    CONSTRAINT fk_jp_class_student_student FOREIGN KEY (student_id) REFERENCES jp_student (id),
    CONSTRAINT chk_jp_class_student_dates CHECK (left_at IS NULL OR left_at >= joined_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE jp_attendance (
    id BIGINT NOT NULL,
    institution_id BIGINT NOT NULL,
    class_id BIGINT NOT NULL,
    student_id BIGINT NOT NULL,
    attendance_date DATE NOT NULL,
    attendance_status VARCHAR(32) NOT NULL DEFAULT 'present',
    source VARCHAR(32) NOT NULL DEFAULT 'manual',
    remark VARCHAR(500) NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NULL,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    updated_by BIGINT NULL,
    deleted TINYINT(1) NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_jp_attendance_student_date (class_id, student_id, attendance_date),
    CONSTRAINT fk_jp_attendance_institution FOREIGN KEY (institution_id) REFERENCES jp_institution (id),
    CONSTRAINT fk_jp_attendance_class FOREIGN KEY (class_id) REFERENCES jp_class (id),
    CONSTRAINT fk_jp_attendance_student FOREIGN KEY (student_id) REFERENCES jp_student (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
