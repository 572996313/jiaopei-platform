CREATE TABLE jp_institution (
    id BIGINT NOT NULL,
    org_code VARCHAR(64) NOT NULL,
    org_name VARCHAR(128) NOT NULL,
    short_name VARCHAR(64) NULL,
    contact_name VARCHAR(64) NULL,
    contact_phone VARCHAR(32) NULL,
    province_code VARCHAR(32) NULL,
    city_code VARCHAR(32) NULL,
    district_code VARCHAR(32) NULL,
    address VARCHAR(255) NULL,
    timezone VARCHAR(64) NOT NULL DEFAULT 'Asia/Shanghai',
    status VARCHAR(32) NOT NULL DEFAULT 'draft',
    opened_at DATE NULL,
    remark VARCHAR(500) NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NULL,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    updated_by BIGINT NULL,
    deleted TINYINT(1) NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_jp_institution_org_code (org_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE jp_campus (
    id BIGINT NOT NULL,
    institution_id BIGINT NOT NULL,
    campus_code VARCHAR(64) NOT NULL,
    campus_name VARCHAR(128) NOT NULL,
    campus_type VARCHAR(32) NOT NULL DEFAULT 'direct',
    phone VARCHAR(32) NULL,
    principal_name VARCHAR(64) NULL,
    province_code VARCHAR(32) NULL,
    city_code VARCHAR(32) NULL,
    district_code VARCHAR(32) NULL,
    address VARCHAR(255) NOT NULL,
    capacity_limit INT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'planning',
    opened_at DATE NULL,
    sort_no INT NULL,
    remark VARCHAR(500) NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NULL,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    updated_by BIGINT NULL,
    deleted TINYINT(1) NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_jp_campus_code (institution_id, campus_code),
    UNIQUE KEY uk_jp_campus_name (institution_id, campus_name),
    CONSTRAINT fk_jp_campus_institution FOREIGN KEY (institution_id) REFERENCES jp_institution (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE jp_classroom (
    id BIGINT NOT NULL,
    campus_id BIGINT NOT NULL,
    classroom_code VARCHAR(64) NOT NULL,
    classroom_name VARCHAR(128) NOT NULL,
    room_type VARCHAR(32) NOT NULL DEFAULT 'normal',
    floor_no VARCHAR(32) NULL,
    seat_capacity INT NOT NULL DEFAULT 0,
    area_sqm DECIMAL(10, 2) NULL,
    equipment_tags JSON NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'idle',
    allow_scheduling TINYINT(1) NOT NULL DEFAULT 1,
    remark VARCHAR(500) NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NULL,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    updated_by BIGINT NULL,
    deleted TINYINT(1) NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_jp_classroom_code (campus_id, classroom_code),
    UNIQUE KEY uk_jp_classroom_name (campus_id, classroom_name),
    CONSTRAINT fk_jp_classroom_campus FOREIGN KEY (campus_id) REFERENCES jp_campus (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE jp_term (
    id BIGINT NOT NULL,
    institution_id BIGINT NOT NULL,
    term_code VARCHAR(64) NOT NULL,
    term_name VARCHAR(128) NOT NULL,
    academic_year VARCHAR(16) NOT NULL,
    season VARCHAR(32) NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    enrollment_start_date DATE NULL,
    enrollment_end_date DATE NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'draft',
    is_default TINYINT(1) NOT NULL DEFAULT 0,
    remark VARCHAR(500) NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NULL,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    updated_by BIGINT NULL,
    deleted TINYINT(1) NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_jp_term_code (institution_id, term_code),
    CONSTRAINT fk_jp_term_institution FOREIGN KEY (institution_id) REFERENCES jp_institution (id),
    CONSTRAINT chk_jp_term_date CHECK (start_date <= end_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE jp_time_slot (
    id BIGINT NOT NULL,
    institution_id BIGINT NOT NULL,
    campus_id BIGINT NULL,
    slot_code VARCHAR(64) NOT NULL,
    slot_name VARCHAR(128) NOT NULL,
    weekday TINYINT NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    duration_minutes INT NOT NULL,
    slot_type VARCHAR(32) NOT NULL DEFAULT 'teaching',
    applicable_scene VARCHAR(32) NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'active',
    sort_no INT NULL,
    remark VARCHAR(500) NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NULL,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    updated_by BIGINT NULL,
    deleted TINYINT(1) NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_jp_time_slot_org_code (institution_id, slot_code),
    UNIQUE KEY uk_jp_time_slot_name (institution_id, campus_id, slot_name),
    CONSTRAINT fk_jp_time_slot_institution FOREIGN KEY (institution_id) REFERENCES jp_institution (id),
    CONSTRAINT fk_jp_time_slot_campus FOREIGN KEY (campus_id) REFERENCES jp_campus (id),
    CONSTRAINT chk_jp_time_slot_weekday CHECK (weekday BETWEEN 1 AND 7),
    CONSTRAINT chk_jp_time_slot_time CHECK (start_time < end_time),
    CONSTRAINT chk_jp_time_slot_duration CHECK (duration_minutes > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
