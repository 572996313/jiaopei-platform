CREATE TABLE schedule_lesson (
    id BIGINT NOT NULL,
    institution_id BIGINT NOT NULL,
    campus_id BIGINT NOT NULL,
    term_id BIGINT NOT NULL,
    class_id BIGINT NOT NULL,
    classroom_id BIGINT NOT NULL,
    time_slot_id BIGINT NOT NULL,
    lesson_date DATE NOT NULL,
    lesson_weekday TINYINT NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    lesson_title VARCHAR(128) NULL,
    lesson_status VARCHAR(32) NOT NULL DEFAULT 'scheduled',
    remark VARCHAR(500) NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NULL,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    updated_by BIGINT NULL,
    deleted TINYINT(1) NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    KEY idx_schedule_lesson_day (institution_id, campus_id, lesson_date),
    KEY idx_schedule_lesson_class_slot (class_id, lesson_date, time_slot_id),
    KEY idx_schedule_lesson_classroom_slot (classroom_id, lesson_date, time_slot_id),
    CONSTRAINT fk_schedule_lesson_institution FOREIGN KEY (institution_id) REFERENCES jp_institution (id),
    CONSTRAINT fk_schedule_lesson_campus FOREIGN KEY (campus_id) REFERENCES jp_campus (id),
    CONSTRAINT fk_schedule_lesson_term FOREIGN KEY (term_id) REFERENCES jp_term (id),
    CONSTRAINT fk_schedule_lesson_class FOREIGN KEY (class_id) REFERENCES jp_class (id),
    CONSTRAINT fk_schedule_lesson_classroom FOREIGN KEY (classroom_id) REFERENCES jp_classroom (id),
    CONSTRAINT fk_schedule_lesson_time_slot FOREIGN KEY (time_slot_id) REFERENCES jp_time_slot (id),
    CONSTRAINT chk_schedule_lesson_weekday CHECK (lesson_weekday BETWEEN 1 AND 7),
    CONSTRAINT chk_schedule_lesson_time CHECK (start_time < end_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE schedule_teacher_rel (
    id BIGINT NOT NULL,
    lesson_id BIGINT NOT NULL,
    teacher_id BIGINT NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by BIGINT NULL,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    updated_by BIGINT NULL,
    deleted TINYINT(1) NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    UNIQUE KEY uk_schedule_teacher (lesson_id, teacher_id),
    KEY idx_schedule_teacher_teacher (teacher_id),
    CONSTRAINT fk_schedule_teacher_lesson FOREIGN KEY (lesson_id) REFERENCES schedule_lesson (id),
    CONSTRAINT fk_schedule_teacher_teacher FOREIGN KEY (teacher_id) REFERENCES jp_teacher (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
